/**
 * Application / src/application/PriceMonitorService.js
 * Use cases of the app. Receives the datasets by injection and returns plain view models.
 */
import { basketCost, basketLines, customPurchasingPower, ITEM_CATALOG, neededMinimumWage, priceRange, wagePercent, workTime } from '../domain/BasketCalculator.js?v=20261119-1403';
import { KIND, describeBasket, describeEstate } from '../domain/MunicipalityCoverage.js?v=20261119-1403';
import { COMMERCIAL_MAX_AREA, estimateProperty } from '../domain/RealEstateCalculator.js?v=20261119-1403';
import { bracketLag, compareWithCorrectedTable, correctedBands, grossForBase, roundCents } from '../domain/IncomeTaxCalculator.js?v=20261119-1403';
import { VendorParameters } from '../infrastructure/VendorParameters.js?v=20261119-1403';

/** The exemption of 1996 (R$ 900) is the start of the lag; the IPCA index of the month before it is the start of the inflation. */
const IRPF_LAG_START_DATE = '1996-01-01';
const IRPF_LAG_START_MONTH = '1995-12';
/** Short warning shown with the lag: the figure depends on the base and on the method (Sindifisco gets 157% by another one). */
const LAG_METHOD_WARNING = 'o número depende da base e do método: o Sindifisco chega a 157% por outro método';
const MONTH_NAMES = ['janeiro', 'fevereiro', 'março', 'abril', 'maio', 'junho', 'julho', 'agosto', 'setembro', 'outubro', 'novembro', 'dezembro'];

const normalize = text => String(text).normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase();
const byName = (a, b, key) => a[key].localeCompare(b[key], 'pt-BR');

const CAPITAL_SORTERS = {
  'basket-desc': (a, b) => b.publishedTotal - a.publishedTotal,
  'basket-asc': (a, b) => a.publishedTotal - b.publishedTotal,
  'name-asc': (a, b) => byName(a, b, 'state'),
  'change-desc': (a, b) => b.twelveMonthChange - a.twelveMonthChange,
};

export class PriceMonitorService {
  /**
   * @param {Object} data Datasets generated by scripts/build_data.py
   * @param {import('../infrastructure/VendorParameters.js?v=20261119-1403').VendorParameters} [data.parameters] ParametersPort (common parameter module, ADR-001)
   */
  constructor({ basket, realEstate, municipalities, sources, parameters = new VendorParameters() }) {
    this.parameters = parameters;
    this.basket = basket;
    this.realEstate = realEstate;
    this.municipalities = municipalities;
    this.sources = sources;
    this.citiesByCode = new Map(realEstate.cities.map(city => [city.ibgeCode, city]));
  }

  capitals({ query = '', sort = 'basket-desc' } = {}) {
    const term = normalize(query);
    const sorter = CAPITAL_SORTERS[sort] ?? CAPITAL_SORTERS['basket-desc'];
    return this.basket.capitals
      .filter(c => !term || normalize(`${c.capital} ${c.state} ${c.uf} ${c.macroRegion}`).includes(term))
      .map(c => ({
        ...c,
        wagePercent: wagePercent(c.publishedTotal, this.basket.minimumWage),
        workTime: workTime(c.publishedTotal, this.basket.minimumWage),
      }))
      .sort(sorter);
  }

  overview() {
    const sorted = this.capitals({ sort: 'basket-desc' });
    const total = sorted.reduce((sum, c) => sum + c.publishedTotal, 0);
    return {
      period: this.basket.period,
      highest: sorted[0],
      lowest: sorted[sorted.length - 1],
      average: total / sorted.length,
      neededWage: neededMinimumWage(sorted[0].publishedTotal),
      neededWageMultiple: this.basket.neededWageMultiple,
      minimumWage: this.basket.minimumWage,
      market: this.realEstate.national,
    };
  }

  /** Beans and flour differ by region, so each type is compared only with itself. */
  itemRanking() {
    const groups = [];
    for (const item of ITEM_CATALOG) {
      const typeKey = { beans: 'beansType', flour: 'flourType' }[item.key];
      const types = typeKey ? [...new Set(this.basket.capitals.map(c => c[typeKey]))].sort() : [null];
      for (const type of types) {
        const entries = this.basket.capitals
          .filter(c => c.prices[item.key] != null && (!type || c[typeKey] === type))
          .map(c => ({ capital: c.capital, uf: c.uf, price: c.prices[item.key] }));
        groups.push({ ...item, label: !type ? item.label : item.key === 'flour' ? `${item.label} de ${type}` : `${item.label} ${type}`, ...priceRange(entries) });
      }
    }
    return groups;
  }

  basketBreakdown(ibgeCode) {
    const capital = this.basket.capitals.find(c => c.ibgeCode === ibgeCode);
    if (!capital) throw new RangeError('Capital não encontrada');
    const quantities = this.basket.quantities[capital.decreeRegion];
    return {
      capital,
      lines: basketLines(capital.prices, quantities),
      calculatedTotal: basketCost(capital.prices, quantities),
      publishedTotal: capital.publishedTotal,
    };
  }

  /** An unknown code falls back to the first capital of the dataset. */
  customPurchasingPower({ capitalCode, monthlyWage }) {
    const capital = this.basket.capitals.find(c => c.ibgeCode === capitalCode) ?? this.basket.capitals[0];
    return { capital, ...customPurchasingPower(capital.publishedTotal, monthlyWage) };
  }

  /**
   * All municipalities of SP. Each row says whether the value is the municipality's own survey or a regional
   * reference. The derived figures (share of wage, work time, years of rent) run over whatever value is shown.
   */
  spMunicipalities({ query = '', region = 'ALL' } = {}) {
    const term = normalize(query);
    return this.municipalities
      .filter(m => (region === 'ALL' || m.intermediateRegion === region)
        && (!term || normalize(m.municipality).includes(term)))
      .map(m => {
        const basket = describeBasket(m);
        const residential = describeEstate(m, 'residential', this.citiesByCode);
        const commercial = describeEstate(m, 'commercial', this.citiesByCode);
        return {
          ...m,
          basketView: basket,
          wagePercent: wagePercent(basket.value, this.basket.minimumWage),
          workTime: workTime(basket.value, this.basket.minimumWage),
          estate: { residential, commercial },
          yearsOfRent: estimateProperty({ salePerM2: residential.sale, rentPerM2: residential.rent, area: 1 }).yearsOfRent,
        };
      });
  }

  /** How many municipalities have their own value and how many only a regional reference. */
  spCoverage() {
    const count = predicate => this.municipalities.filter(predicate).length;
    return {
      total: this.municipalities.length,
      basketReal: count(m => m.basketKind === KIND.REAL),
      basketReference: count(m => m.basketKind === KIND.REFERENCE),
      residentialReal: count(m => m.realEstate.residential.kind === KIND.REAL),
      residentialReference: count(m => m.realEstate.residential.kind === KIND.REFERENCE),
      commercialReal: count(m => m.realEstate.commercial.kind === KIND.REAL),
      commercialReference: count(m => m.realEstate.commercial.kind === KIND.REFERENCE),
    };
  }

  spRegions() {
    return [...new Set(this.municipalities.map(m => m.intermediateRegion))].sort((a, b) => a.localeCompare(b, 'pt-BR'));
  }

  realEstateCities({ query = '', segment = 'residential', sort = 'sale-desc' } = {}) {
    const term = normalize(query);
    const saleKey = `${segment}Sale`;
    const rentKey = `${segment}Rent`;
    const descending = (key) => (a, b) => (b[key] ?? -1) - (a[key] ?? -1);
    const sorters = {
      'sale-desc': descending(saleKey),
      'rent-desc': descending(rentKey),
      'yield-desc': descending(`${segment}Yield`),
      'name-asc': (a, b) => byName(a, b, 'city'),
    };
    return this.realEstate.cities
      .filter(c => c[saleKey] != null || c[rentKey] != null)
      .filter(c => !term || normalize(`${c.city} ${c.state} ${c.uf} ${c.macroRegion}`).includes(term))
      .sort(sorters[sort] ?? sorters['sale-desc']);
  }

  estimate({ ibgeCode, segment, area }) {
    const city = this.citiesByCode.get(ibgeCode);
    if (!city) throw new RangeError('Cidade não encontrada');
    return {
      city,
      area,
      exceedsCommercialSample: segment === 'commercial' && area > COMMERCIAL_MAX_AREA,
      publishedYield: city[`${segment}Yield`],
      ...estimateProperty({ salePerM2: city[`${segment}Sale`], rentPerM2: city[`${segment}Rent`], area }),
    };
  }
  /** Months of the IPCA index available to measure the lag (after the start month), oldest first, as { value: 'aaaa-mm', label }. */
  lagMonths(on = new Date()) {
    const index = this.parameters.value('ipca_numero_indice', on) ?? {};
    return Object.keys(index).filter(month => month > IRPF_LAG_START_MONTH).sort().map(month => {
      const [year, number] = month.split('-');
      return { value: month, label: `${MONTH_NAMES[Number(number) - 1]} de ${year}` };
    });
  }

  /**
   * How much the IRPF table lags behind inflation since 1996, and, if a gross salary is given, what the employee would pay
   * with the corrected table (spec 3.3). Reads the table of the law in force on `on` and the IPCA index (RN-M01).
   * The salary is only used in this call: nothing is stored.
   * @param {Object} [params]
   * @param {number} [params.grossIncome] Salário bruto mensal (R$); omitted or 0 skips the personal comparison
   * @param {string} [params.untilMonth='2025-12'] Month of the IPCA index the inflation runs to ('aaaa-mm')
   * @param {Date|string} [params.on] Date of the law in force (default: today)
   * @returns {{lag: Object, personal: Object|null}}
   *   lag: { valor: {lagPct, correctedExemption, factor}, selo, insumos, avisos, base, correctedBands (null without a table on the date), effective (null before the Lei 15.270), ... }
   *   personal: { valor: chain of the salary, selo, insumos, avisos } or null
   * @throws {RangeError} month without IPCA index, negative / non-finite salary, or no IRPF / INSS table on the date
   */
  incomeTaxLag({ grossIncome = 0, untilMonth = '2025-12', on = new Date() } = {}) {
    if (!Number.isFinite(grossIncome) || grossIncome < 0) throw new RangeError('O salário bruto deve ser um número maior ou igual a zero');
    const index = this.parameters.value('ipca_numero_indice', on);
    if (!index || !(untilMonth in index) || !(IRPF_LAG_START_MONTH in index) || untilMonth <= IRPF_LAG_START_MONTH) {
      throw new RangeError(`Sem número-índice do IPCA para ${untilMonth}`);
    }
    const startExemption = this.parameters.value('irpf_isencao_mensal', IRPF_LAG_START_DATE);
    const currentExemption = this.parameters.value('irpf_isencao_mensal', on);
    const inflationFactor = index[untilMonth] / index[IRPF_LAG_START_MONTH];
    const raw = bracketLag({ inflationFactor, correctionFactor: currentExemption / startExemption, exemptionLimit: currentExemption });

    const lagInputs = [
      this.parameters.input('ipca_numero_indice', on),
      this.parameters.input('irpf_isencao_mensal', IRPF_LAG_START_DATE),
      this.parameters.input('irpf_isencao_mensal', on)
    ];
    const law = this.parameters.value('tabela_irpf_mensal', on);
    const inssBands = this.parameters.value('tabela_inss_empregado', on)?.faixas;
    const correctedExemption = roundCents(raw.valor.correctedExemption);
    // Second view (Daniel, 19/11/2026): the Lei 15.270 reduction makes whoever earns up to R$ 5.000 gross pay nothing;
    // the corrected exemption, in the same gross terms, protects more. Only exists where the law has the reduction.
    let effective = null;
    if (law?.reducao && inssBands) {
      const correctedGross = grossForBase(correctedExemption, { inssBands, simplifiedDiscount: law.descontoSimplificado });
      effective = { currentGross: law.reducao.limiteIsentoBruto, correctedGross };
      effective.pctAbove = (correctedGross / effective.currentGross - 1) * 100;
    }

    const lag = {
      valor: raw.valor, avisos: [LAG_METHOD_WARNING], insumos: lagInputs,
      // Decidido pelo Celso em 19/11/2026: estimativa, porque o número depende da base e do método (formulaExata = false)
      selo: this.parameters.seal(lagInputs, false),
      base: `Só a faixa de isenção, do IPCA de ${IRPF_LAG_START_MONTH.split('-').reverse().join('/')} a ${untilMonth.split('-').reverse().join('/')}; a redução da Lei 15.270 não entra neste número`,
      untilMonth, startExemption, currentExemption, inflationFactor, correctedExemption,
      correctedBands: law ? correctedBands(law.faixas, raw.valor.factor) : null, effective,
    };

    let personal = null;
    if (grossIncome > 0) {
      if (!law) throw new RangeError('Sem tabela do IRPF em vigor na data');
      if (!inssBands) throw new RangeError('Sem tabela do INSS em vigor na data');
      const inputs = [...lagInputs, this.parameters.input('tabela_irpf_mensal', on), this.parameters.input('tabela_inss_empregado', on)];
      personal = {
        valor: compareWithCorrectedTable({ grossIncome, law, inssBands, lagFactor: raw.valor.factor }),
        avisos: [], insumos: inputs, selo: this.parameters.seal(inputs, false), // depende do fator de defasagem, que é estimativa
      };
    }
    return { lag, personal };
  }
}
